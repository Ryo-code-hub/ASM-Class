/*===============================================================
 *  SUM.C     作业3 第(3)问
 *  用 C 语言求 1 + 2 + ... + 100，并输出 5050
 *
 *  编译：cl /nologo /Od /c SUM.C
 *        然后 dumpbin /nologo /disasm SUM.obj
 *  运行：SUM.EXE
 *
 *  反汇编结果和逐条注释见同目录的 DISASM.TXT
 *===============================================================*/
#include <stdio.h>

int main(void)
{
    int i;                  /* 循环变量  —— 编译器会把它放在【栈】上 */
    int sum = 0;            /* 累加器    —— 编译器也会把它放在【栈】上 */

    for (i = 1; i <= 100; i++)
        sum = sum + i;      /* 对应汇编里的  ADD AX,BX */

    printf("%d\n", sum);    /* 输出 5050 */

    return 0;
}
